def read_sheets():
    import openpyxl
    wb = openpyxl.load_workbook(XLSX, data_only=True)

    def table(name, header_row=2):
        rows = list(wb[name].iter_rows(values_only=True))
        head = [('' if c is None else str(c).strip()) for c in rows[header_row]]
        out = []
        for r in rows[header_row + 1:]:
            if not any(c is not None and str(c).strip() != '' for c in r):
                continue
            out.append({head[i]: r[i] for i in range(min(len(head), len(r)))})
        return out

    return {
        'campaign': table('12월마감_캠페인'),
        'urgent': table('11월마감_긴급'),
        'ending': table('주의_정산종료'),
        'blocked': table('주의_신규불가_품절'),
        'summary': table('요약'),
    }


def num(v, default=0):
    try:
        return float(str(v).replace(',', '').strip())
    except (TypeError, ValueError):
        return default


def fmt(v):
    """숫자면 3자리 콤마, 아니면 문자열 그대로"""
    if isinstance(v, (int, float)):
        f = float(v)
        return ('{:,.0f}'.format(f)) if abs(f - round(f)) < 1e-9 else ('{:,.1f}'.format(f))
    return '' if v is None else str(v).strip()


def rate(v):
    f = num(v)
    return ('{:g}'.format(f)) + '%'


def period(o):
    s, e = fmt(o.get('시작')), fmt(o.get('마감'))
    if s and e:
        return s + ' ~ ' + e
    return e or s


def extra_memo(row):
    """'2026.xx EDI까지 정산 가능' 같은 기본 문구 말고 실제 덧붙일 내용만"""
    memo = fmt(row.get('비고(원문)'))
    memo = re.sub(r'\s*/?\s*2026\.\d{2} EDI까지 정산 가능\s*/?', ' ', memo).strip(' /')
    return (' · ' + memo) if memo else ''


def block(name, title):
    return '\n\n■ ' + title + '\n' + '─' * 34 + '\n'


